-- Seções fixas da DRE gerencial + subgrupos de categorias + configurações avançadas da empresa

CREATE TYPE "DRESection" AS ENUM ('OPERATING_REVENUE', 'OPERATING_COSTS', 'OPERATING_EXPENSES', 'INVESTING', 'FINANCING');

ALTER TABLE "categories"
  ADD COLUMN "isGroup" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN "section" "DRESection";

-- Converte os grupos antigos para as seções (transferências ficam fora da DRE)
UPDATE "categories" SET "section" = CASE "dreGroup"::text
  WHEN 'REVENUE_GROSS' THEN 'OPERATING_REVENUE'
  WHEN 'REVENUE_DEDUCTIONS' THEN 'OPERATING_REVENUE'
  WHEN 'DIRECT_COSTS' THEN 'OPERATING_COSTS'
  WHEN 'EXPENSE_COMMERCIAL' THEN 'OPERATING_EXPENSES'
  WHEN 'EXPENSE_ADMINISTRATIVE' THEN 'OPERATING_EXPENSES'
  WHEN 'EXPENSE_PERSONNEL' THEN 'OPERATING_EXPENSES'
  WHEN 'FINANCIAL_EXPENSE' THEN 'OPERATING_EXPENSES'
  WHEN 'NON_OPERATIONAL' THEN 'OPERATING_EXPENSES'
  WHEN 'TAXES_ON_PROFIT' THEN 'OPERATING_EXPENSES'
  WHEN 'FINANCIAL_REVENUE' THEN 'INVESTING'
  WHEN 'EQUITY_DISTRIBUTION' THEN 'FINANCING'
  ELSE NULL
END::"DRESection";

DROP INDEX "categories_companyId_dreGroup_idx";
ALTER TABLE "categories" DROP COLUMN "dreGroup";
DROP TYPE "DREGroup";
CREATE INDEX "categories_companyId_section_idx" ON "categories"("companyId", "section");

ALTER TABLE "companies"
  ADD COLUMN "accrualBasis" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN "costCentersEnabled" BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN "provisioningMonths" INTEGER NOT NULL DEFAULT 12;
